// Generates core/src/team/state.rs from core/schema/team.json: one Rust struct per object kind, loaded from the
// JSON written by scripts/lib/team-state.mjs and digested exactly like digestState() (RUST-CORE.md, phase B).
// node scripts/gen-rust-state.mjs [--check]   (run after scripts/rust-schema.mjs; the output is committed;
// --check only verifies that the committed file is what the schema generates)
import fs from 'node:fs';

const schema=JSON.parse(fs.readFileSync('core/schema/team.json','utf8')),kinds=schema.kinds;
const KEYWORDS=new Set(['as','break','const','continue','crate','else','enum','extern','false','fn','for','if','impl','in','let','loop','match','mod','move','mut','pub','ref','return','self','Self','static','struct','super','trait','true','type','unsafe','use','where','while','async','await','dyn','abstract','become','box','do','final','macro','override','priv','typeof','unsized','virtual','yield','try']);
const structName=kind=>kind.split(/[^A-Za-z0-9]+/).filter(Boolean).map(p=>p[0].toUpperCase()+p.slice(1)).join('');
const snake=key=>{let s=key.replace(/([a-z0-9])([A-Z])/g,'$1_$2').replace(/[^A-Za-z0-9_]/g,'_').toLowerCase();if(/^[0-9]/.test(s))s='f_'+s;if(/^[A-Z]+$/.test(key))s=key.toLowerCase()+'_upper';return KEYWORDS.has(s)?s+'_':s;};
function alternatives(type){const out=[];let depth=0,start=0;for(let i=0;i<type.length;i++){const c=type[i];if(c==='<')depth++;else if(c==='>')depth--;else if(c==='|'&&depth===0){out.push(type.slice(start,i));start=i+1;}}out.push(type.slice(start));return out;}
const inner=t=>t.slice(t.indexOf('<')+1,-1);
const unions=new Map();
// Rust type for a schema type (without the field's own nullability).
function rust(type){
 const alts=alternatives(type);
 if(alts.length>1){
  const names=alts.map(a=>a==='f64'?'Num':a==='str'?'Str':a==='entity'?'Ent':a.startsWith('obj<')?'Obj':null);if(names.includes(null))throw new Error(`unsupported union ${type}`);
  const name=alts.map(a=>a==='f64'?'Num':a==='str'?'Str':a==='entity'?'Ent':structName(inner(a))).join('Or');
  unions.set(name,alts);return name;
 }
 const t=alts[0];
 if(t==='f64')return 'f64';if(t==='bool')return 'bool';if(t==='str')return 'String';if(t==='entity')return 'Ent';if(t==='null'||t==='?')return 'Never';
 if(t.startsWith('arr<')||t.startsWith('set<')){const el=t.slice(4,-1),opt=el.length>1&&el.endsWith('?'),base=opt?el.slice(0,-1):el;const r=rust(base);return `Vec<${opt?`Option<${r}>`:r}>`;}
 if(t.startsWith('obj<'))return structName(inner(t));
 if(t.startsWith('map<')){const k=kinds[inner(t)];return `JsMap<${rust(k.fields['{}']?.type??'f64')}>`;}
 throw new Error(`unsupported type ${t}`);
}
// The digest call for a value expression of the given schema type.
function digest(type,expr,nullable,engineOnly){
 if(engineOnly)return `match ${expr}.present() { None => h.nil(), Some(v) => { ${digest(type,'(*v)',false)} } }`;
 if(nullable)return `match &${expr} { None => h.nil(), Some(v) => { ${digest(type,'(*v)',false)} } }`;
 const alts=alternatives(type);if(alts.length>1)return `${expr}.digest(h);`;
 const t=alts[0];
 if(t==='f64')return `h.f64(${expr});`;if(t==='bool')return `h.bool(${expr});`;if(t==='str')return `h.str(&${expr});`;if(t==='entity')return `h.ent(${expr});`;
 if(t==='null'||t==='?')return `h.nil();`;
 if(t.startsWith('arr<')||t.startsWith('set<')){const el=t.slice(4,-1),opt=el.length>1&&el.endsWith('?'),base=opt?el.slice(0,-1):el;return `h.arr(${expr}.len()); for x in ${expr}.iter() { ${digest(base,'(*x)',opt)} }`;}
 if(t.startsWith('obj<'))return `${expr}.digest(h);`;
 if(t.startsWith('map<')){const k=kinds[inner(t)],vt=k.fields['{}']?.type??'f64';return `h.map(${expr}.len()); for (k, v) in ${expr}.iter() { h.key(k); ${digest(vt,'(*v)',false)} }`;}
 throw new Error(`unsupported type ${t}`);
}
const out=[`// Generated by scripts/gen-rust-state.mjs from core/schema/team.json. Do not edit by hand.
// One struct per object kind of a running ${schema.engines.join(' or ')} battle; loads the JSON from scripts/lib/team-state.mjs and
// digests exactly like its digestState().
#![allow(clippy::all, non_snake_case, dead_code, unused_parens, unused_variables)]
use super::jsnum::{self, Ent, JsDe, JsMap, Never, Opt};
use super::digest::{Digest, Fnv};
use serde::Deserialize;
`];
for(const [kind,spec] of Object.entries(kinds)){
 if(spec.map)continue;
 const name=structName(kind),fields=Object.entries(spec.fields),used=new Set();
 out.push(`/// \`${kind}\`\n#[derive(Debug, Clone, Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct ${name} {`);
 const digestLines=[];
 for(const [key,{type,nullable,engines}] of fields){
  let field=snake(key);while(used.has(field))field+='_';used.add(field);
  // A non-nullable field some engines lack is an Opt (reads as the value; missing only in the other engines).
  const engineOnly=!!engines&&!nullable,base=rust(type),ty=nullable?`Option<${base}>`:engineOnly?`Opt<${base}>`:base;
  const attrs=[`rename = "${key}"`];if(nullable||engineOnly)attrs.push('default');
  // Numbers go through jsnum so −0, NaN and ±Infinity survive ({"$f": bits}).
  const prefix=nullable?'opt_':engineOnly?'eng_':'';
  if(base==='f64')attrs.push(`deserialize_with = "jsnum::${prefix}f64"`);
  else if(base==='Vec<f64>')attrs.push(`deserialize_with = "jsnum::${prefix}vec_f64"`);
  else if(base==='Vec<Vec<f64>>'){if(nullable)throw new Error(`${kind}.${key}: nullable lists of lists are not supported`);attrs.push(`deserialize_with = "jsnum::${prefix}vec_vec_f64"`);}
  out.push(`    #[serde(${attrs.join(', ')})]\n    pub ${field}: ${ty},`);
  digestLines.push(`        ${digest(type,`self.${field}`,nullable,engineOnly)}`);
 }
 out.push(`}\nimpl JsDe for ${name} {}\nimpl Digest for ${name} {\n    fn digest(&self, h: &mut Fnv) {\n        h.obj();\n${digestLines.join('\n')}\n    }\n}\n`);
}
for(const [name,alts] of unions){
 const variants=alts.map(a=>a==='f64'?['Num','f64']:a==='str'?['Str','String']:a==='entity'?['Ent','Ent']:['Obj',structName(inner(a))]);
 out.push(`/// One of: ${alts.join(' | ')}\n#[derive(Debug, Clone)]\npub enum ${name} {\n${variants.map(([v,t])=>`    ${v}(${t}),`).join('\n')}\n}`);
 out.push(`impl<'de> Deserialize<'de> for ${name} {\n    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {\n        let v = serde_json::Value::deserialize(d)?;\n${variants.map(([v,t])=>v==='Num'?`        if let Some(x) = jsnum::value_f64(&v) { return Ok(${name}::Num(x)); }`:v==='Str'?`        if let serde_json::Value::String(s) = &v { return Ok(${name}::Str(s.clone())); }`:v==='Ent'?`        if let Some(e) = jsnum::value_ent(&v) { return Ok(${name}::Ent(e)); }`:`        if v.is_object() { return ${t}::deserialize(v).map(${name}::Obj).map_err(serde::de::Error::custom); }`).join('\n')}\n        Err(serde::de::Error::custom("${name}: unexpected value"))\n    }\n}`);
 out.push(`impl Digest for ${name} {\n    fn digest(&self, h: &mut Fnv) {\n        match self {\n${variants.map(([v,t])=>`            ${name}::${v}(x) => { ${v==='Num'?'h.f64(*x);':v==='Str'?'h.str(x);':v==='Ent'?'h.ent(*x);':'x.digest(h);'} }`).join('\n')}\n        }\n    }\n}\n`);
}
const text=out.join('\n')+'\n';
// The same schema as a module for the game (public/battle-state.js exports battles for the WebAssembly core).
const jsText=`// Generated by scripts/gen-rust-state.mjs from core/schema/team.json: the state schema the Rust core loads.\nexport const TEAM_STATE_SCHEMA=${JSON.stringify({engines:schema.engines,kinds})};\n`;
if(process.argv.includes('--check')){
 if(fs.readFileSync('core/src/team/state.rs','utf8')!==text){console.error('core/src/team/state.rs is out of date: run node scripts/gen-rust-state.mjs');process.exit(1);}
 if(fs.readFileSync('public/team-state-schema.js','utf8')!==jsText){console.error('public/team-state-schema.js is out of date: run node scripts/gen-rust-state.mjs');process.exit(1);}
 console.log('core/src/team/state.rs and public/team-state-schema.js match the schema');process.exit(0);}
fs.mkdirSync('core/src/team',{recursive:true});
fs.writeFileSync('core/src/team/state.rs',text);fs.writeFileSync('public/team-state-schema.js',jsText);
console.log(`core/src/team/state.rs: ${Object.values(kinds).filter(k=>!k.map).length} structs, ${unions.size} unions`);
